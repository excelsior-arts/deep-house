/** The names above that match no row: the runner refuses the run with them (a renamed row keeps its tier by name). */
export function staleTierNames(rows: ReadonlyArray<{ name: string }>): string[] {
  const names = new Set(rows.map((r) => r.name));
  return [...GATE, ...WEEKLY, ...MEASURE, ...FIREFOX].filter((n) => !names.has(n));
}

/** Each row's tier and its marks, from the tables above (a row's own field, where it names one, wins). */
export function applyTiers<T extends { name: string; tier?: string; measure?: boolean; firefox?: boolean; serial?: boolean }>(rows: T[]): T[] {
  for (const r of rows) {
    r.tier ??= GATE.has(r.name) ? 'gate' : WEEKLY.has(r.name) ? 'weekly' : 'night';
    if (MEASURE.has(r.name)) { r.measure ??= true; r.serial = false; }
    if (FIREFOX.has(r.name)) r.firefox ??= true;
  }
  return rows;
}
